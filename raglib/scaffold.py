def _provider(llm: str):
    """Return the ProviderSpec for ``llm`` (``None`` for mock or unknown providers)."""

    from raglib.llm.providers import PROVIDERS, parse_model_string

    name = parse_model_string(llm)[0] if llm else None
    return PROVIDERS.get(name or "")


def _models(llm: str) -> Tuple[str, Optional[str], str, Optional[str]]:
    """``(chat key env var, embedding provider, embedding key env var, note)`` for the chat provider."""

    if (llm or "").strip().lower() in {"mock", "offline"}:
        return "", "mock", "", None
    spec = _provider(llm)
    chat_env = spec.env_keys[0] if spec is not None and spec.env_keys and spec.requires_key else ""
    if spec is not None and spec.default_embedding_model:
        return chat_env, spec.name, chat_env, None
    # Chat providers without an embeddings API (OpenRouter, Anthropic, Groq, ...): OpenAI embeddings.
    note = f"{spec.name if spec else 'this provider'} has no embeddings API; using OpenAI embeddings"
    return chat_env, "openai", "OPENAI_API_KEY", note


def _getenv(name: str) -> str:
    return f'os.getenv("{name}")' if name else "None"


def render_pipeline(preset: str = "production", llm: str = "openai", docs: str = "docs/", script: str = "rag_pipeline.py") -> str:
    """Return the source of a pipeline file with every ``RAG`` option written out."""

    values = resolve_preset(preset)
    chat_env, embedding, embedding_env, _ = _models(llm)
    tokens: Dict[str, str] = {
        "<<PRESET>>": preset,
        "<<DOCS_REPR>>": repr(docs).replace("'", '"'),
        "<<SCRIPT>>": script,
        "<<DOCS_URL>>": DOCS_URL,
        "<<PRESETS_URL>>": PRESETS_DOCS_URL,
        "<<LLM_REPR>>": f'"{llm}"',
        "<<CHAT_KEY>>": _getenv(chat_env),
        "<<EMBEDDING_REPR>>": f'"{embedding}"',
        "<<EMBEDDING_KEY>>": _getenv(embedding_env),
        "<<CHUNK_SIZE>>": str(values.get("chunk_size", 400)),
        "<<CHUNK_OVERLAP>>": str(values.get("chunk_overlap", 50)),
        "<<TOP_K>>": str(values.get("top_k", 5)),
        "<<RERANKER_REPR>>": f'"{values.get("reranker", "none")}"',
        "<<RERANK_CANDIDATES>>": str(values.get("rerank_candidates")),
        "<<EMBEDDING_TTL>>": repr(values.get("embedding_cache_ttl")),
        "<<TOKEN_COUNTER>>": f'"{values.get("token_counter", "units")}"',
        "<<ON_FAILURE>>": f'"{values.get("on_embedding_failure", "fallback")}"',
        "<<OVERSIZED>>": f'"{values.get("oversized_chunks", "split")}"',
    }
    source = PIPELINE_TEMPLATE
    for token, value in tokens.items():
        source = source.replace(token, value)
    # Keep the comments of the option lines in one column after the values were filled in.
    return re.sub(
        r"(?m)^(    [a-z_]+=.*?,)[ ]+(# .*)$",
        lambda match: f"{match.group(1).ljust(_COMMENT_COLUMN - 1)} {match.group(2)}",
        source,
    )


def render_env(llm: str = "openai", extra: Sequence[str] = ()) -> str:
    """Return a ``.env.example`` with the credentials the generated pipeline reads."""

    chat_env, _, embedding_env, note = _models(llm)
    spec = _provider(llm)
    lines = ["# Copy to .env and fill in. Never commit .env."]
    if spec is not None:
        lines.append(f"# Chat model: {spec.description or spec.name}")
    lines.append(f"{chat_env}=" if chat_env else "# The chat model needs no API key.")
    if embedding_env and embedding_env != chat_env:
        lines += [f"# Embeddings ({note})" if note else "# Embeddings", f"{embedding_env}="]
    if spec is not None and spec.base_url_env:
        lines.append(f"# {spec.base_url_env[0]}=   # optional: custom endpoint")
    lines += ["# Only if you switch the reranker to Cohere:", "# COHERE_API_KEY=", *extra]
    return "\n".join(lines) + "\n"


def write_scaffold(
    path: str = "rag_pipeline.py",
    preset: str = "production",
    llm: str = "openai",
    docs: str = "docs/",
    force: bool = False,
) -> List[Path]:
    """Write the pipeline file and ``.env.example`` next to it; returns the written paths.

    Refuses to overwrite an existing pipeline file unless ``force``; an existing
    ``.env.example`` is left alone (it may hold your edits).
    """

    target = Path(path)
    if target.suffix != ".py":
        target = target / "rag_pipeline.py" if target.is_dir() or not target.suffix else target.with_suffix(".py")
    if target.exists() and not force:
        raise FileExistsError(f"{target} already exists (use --force to overwrite)")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_pipeline(preset=preset, llm=llm, docs=docs, script=target.name), encoding="utf-8")
    written = [target]
    env_example = target.with_name(".env.example")
    if not env_example.exists() or force:
        env_example.write_text(render_env(llm), encoding="utf-8")
        written.append(env_example)
    return written


def next_steps(written: Sequence[Path], docs: str, llm: Optional[str]) -> str:
    """Human-readable instructions printed after the files are written."""

    pipeline = written[0]
    lines = [f"Wrote {path}" for path in written]
    lines += [
        "",
        f"{pipeline} lists every RAG option with its production value - edit any line.",
        "",
        "Next steps:",
        f"  1. copy {pipeline.with_name('.env.example')} to {pipeline.with_name('.env')} and add your keys",
        f"  2. put your documents in {docs}",
        f'  3. python {pipeline} "Your question?"',
        "",
        f"To customize more, read the docs: {DOCS_URL}",
    ]
    return "\n".join(lines)
